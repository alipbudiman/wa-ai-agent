from datetime import datetime
import json
import os
import logging
from langchain_tavily import TavilySearch
from langchain_core.tools import StructuredTool

from backend.application.ai.tools.models import WebSearchInput
from backend.application.ai.tools.whatsapp_integration import WhatsAppIntegration
from config.config import Config
from langchain_community.document_loaders import WikipediaLoader


logger = logging.getLogger('uvicorn.error')


class WebSearchTool:
    """Web search utility that fetches Tavily results and summarizes them with the LLM."""

    def __init__(self):
        """Initialize the web search tool with an LLM client and WhatsApp integration helper."""
        self.wa_bot = WhatsAppIntegration()
        self.config = Config()
    
    def _extract_tavily_results(self, raw_results) -> list:
        """Normalize Tavily output into a list of result dictionaries."""

        if isinstance(raw_results, str):
            try:
                raw_results = json.loads(raw_results)
            except json.JSONDecodeError:
                return []

        if isinstance(raw_results, dict):
            results = raw_results.get('results', [])
        elif isinstance(raw_results, list):
            results = raw_results
        else:
            return []

        normalized = []
        for item in results:
            if not isinstance(item, dict):
                continue

            normalized.append({
                'title': str(item.get('title', 'Untitled')),
                'url': str(item.get('url', '-')),
                'summary': str(item.get('summary') or item.get('content') or ''),
            })

        return normalized
    
    def websearch(self, sender: str, query: str, topic: str = 'general', max_results: int = 5) -> str:
        """
        Search the web via Tavily and return an LLM-generated summary.

        This tool is designed for the active conversation flow. The `sender`
        argument is INTERNAL and injected by the system runtime (graph state),
        so the model/user should not provide it manually.


        Args:
            query: The search question/keywords from user intent.
            sender: Internal active chat user ID/JID injected by runtime,
                used for progress notification.
            topic: Tavily topic selection (`general` by default; `news` for
                recent events).

        Returns:
            A summarized answer generated by the LLM, or a fallback text when
            no web results are found.

        Raises:
            ValueError: If `TAVILY_API_KEY` is not configured.
        """
        tavily_apikey = self.config.get_tavily_config().api_key
        if tavily_apikey:
            os.environ['TAVILY_API_KEY'] = tavily_apikey

        if not os.getenv('TAVILY_API_KEY'):
            raise ValueError('TAVILY_API_KEY is not set. Add it to your environment file.')
        
        time_humanize_now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        
        self.wa_bot.request_send_message(sender, f"🌐Performing web search for query: '{query}' with topic: '{topic}'", sender)
        
        tavily_search_tool = TavilySearch(
            max_results=max_results,
            topic=topic
        )
        
        query = f"{query} (Search Date: {time_humanize_now})"
        raw_results = tavily_search_tool.run(query)
        results = self._extract_tavily_results(raw_results)
        if not results:
            return 'No web results found for that query.'

        summerized_results = []
        source_urls = []
        for result in results:
            summerized_results.append(f"Title: {result['title']}\nURL: {result['url']}\nSummary: {result['summary']}\n")
            source_urls.append(result['url'])
            logger.info(
                "Tavily result:\nTitle: %s\nURL: %s\nSummary: %s\n",
                result['title'],
                result['url'],
                result['summary'],
            )
        
        res = f"Here are the search results for the query: '{query}':\n\n" + "\n".join(summerized_results)
        
        source_str = " , ".join(source_urls)
        self.wa_bot.request_send_message(sender, f"👌 Web search completed. Sources: {source_str}", sender)
        
        return res

    def websearch_tool(self, sender: str):
        """
        Return the StructuredTool wrapper for LLM tool-calling.

        The wrapper injects `sender` from system state and only exposes
        user-facing args (`query`, `topic`) to tool-calling.
        """
        
        def _web(query: str, topic: str = 'general') -> str:
            return self.websearch(sender=sender, query=query, topic=topic)
        
        return StructuredTool.from_function(
            func=_web,
            name="websearch",
            description=(
                "Use this tool for simple external or up-to-date lookups that need one direct web search. "
                "Do not use this as the main tool when the user explicitly asks for research/riset, "
                "deep research, multi-source analysis, comparison, trends, market/news/background research, "
                "or detailed sourced synthesis; use research_agent_tool instead. "
                "Search the web and summarize findings for the current chat request. "
                "`sender` is injected by system runtime from active chat context; "
                "do not ask user for sender and do not include sender in tool args."
            ),
            args_schema=WebSearchInput,
        )
    
    def search_wikipedia(self, question: str) -> str:
        """ search wikipedia and return formatted results. for search on wikipedia, we can directly return the search result without sending progress notification to user, because wikipedia search is usually fast enough and we can include the search result in the conversation flow seamlessly without breaking the user experience. """
        try:
            search_docs = WikipediaLoader(query=question, load_max_docs=2).load()
        except Exception as err:
            logger.warning("Wikipedia search failed for query '%s': %s", question, err)
            return "No relevant Wikipedia data available."

        if not search_docs:
            return "No relevant Wikipedia data available."

        formatted_search_docs = "\n\n---\n\n".join(
            [
                (
                    f'<Document source="{doc.metadata.get("source", "-")}" '
                    f'page="{doc.metadata.get("page", "")}">\n'
                    f"{doc.page_content}\n</Document>"
                )
                for doc in search_docs
                if getattr(doc, "page_content", "").strip()
            ]
        )

        return formatted_search_docs or "No relevant Wikipedia data available."


